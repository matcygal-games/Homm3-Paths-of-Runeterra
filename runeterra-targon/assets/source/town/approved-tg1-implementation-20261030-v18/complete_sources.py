def read_pin(project,reference):
    name=reference['path'];path=(project/name).resolve()
    if not path.is_relative_to(project.resolve())or path.absolute()!=project/name or path.stat().st_nlink!=1:
        raise ValueError('Aliased/outside candidate input')
    if core.sha(path)!=reference['sha256']:raise ValueError('Candidate input changed: '+name)
    return path

def compile_recipes(recipes):
    compiler=compiler_module.create_compiler('targon');passes=[];first=None
    for ordinal in range(2):
        outputs={}
        for path in recipes:
            actual,_=compiler.plan(PROJECT,path)
            if outputs.keys()&actual.keys():raise ValueError('Duplicate native output producer')
            outputs.update(actual)
        pins={name:hashlib.sha256(raw).hexdigest()for name,raw in sorted(outputs.items())}
        passes.append(pins)
        if ordinal==0:first=outputs
    if passes[0]!=passes[1]:raise ValueError('Native converter nondeterministic')
    return first,passes[0]

def inspect_generated(outputs,design,content):
    """Run unchanged inspect() with exact generated bytes in a private process.

    Only candidate design and generated resource reads are overlaid. Source
    paths, source pins, masks and contracts use real strict filesystem checks.
    This is a source/consumer test, never execution of C++ or a live stage.
    """
    virtual={(PROJECT/'assets/generated'/name).resolve():raw for name,raw in outputs.items()}
    previous_read=layout.fp.read_json;previous_sha=layout.fp.sha256;previous_open=Image.open
    def read(path):
        path=Path(path).resolve()
        if path==PROJECT/'design/town-visuals.json':return deepcopy(design)
        if path in virtual:return json.loads(virtual[path])
        return previous_read(path)
    def sha(path):
        path=Path(path).resolve()
        return hashlib.sha256(virtual[path]).hexdigest()if path in virtual else previous_sha(path)
    def opened(path,*args,**kwargs):
        if isinstance(path,(str,Path))and Path(path).resolve()in virtual:
            return previous_open(io.BytesIO(virtual[Path(path).resolve()]),*args,**kwargs)
        return previous_open(path,*args,**kwargs)
    with patch.object(layout.fp,'read_json',read),patch.object(layout.fp,'sha256',sha),patch.object(Image,'open',opened):
        return layout.inspect(PROJECT,{'factions':content},'targon')

